// Storage can be blocked, and the panel must still open: English is then simply what it shows.
function storedLanguage() {
  try {
    const saved = localStorage.getItem(LANGUAGE_KEY);
    return Object.keys(I18N).includes(saved) ? saved : "en";
  } catch {
    return "en";
  }
}

const LANG = storedLanguage();

function t(key, values = {}) {
  return I18N[LANG][key].replace(/\{(\w+)\}/g, (_, name) => values[name]);
}

function applyPageText() {
  document.documentElement.lang = LANG;
  for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll("[data-i18n-placeholder]")) node.placeholder = t(node.dataset.i18nPlaceholder);
  for (const node of document.querySelectorAll("[data-i18n-label]")) node.setAttribute("aria-label", t(node.dataset.i18nLabel));
}

function setUpLanguageSwitches() {
  for (const select of document.querySelectorAll(".language-switch")) {
    for (const [code, name] of Object.entries(LANGUAGE_NAMES)) {
      const option = document.createElement("option");
      option.value = code;
      option.textContent = name;
      option.selected = code === LANG;
      select.append(option);
    }
    select.addEventListener("change", () => {
      try {
        localStorage.setItem(LANGUAGE_KEY, select.value);
      } catch {
        return; // nowhere to remember it, and a reload would only bring English back
      }
      location.reload();
    });
  }
}

applyPageText();
setUpLanguageSwitches();
